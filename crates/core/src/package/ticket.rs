const TITLE_KEY_OFF: usize = 0x1BF - SIG_BLOCK;
const TITLE_ID_OFF: usize = 0x1DC - SIG_BLOCK;

/// Encrypt a decrypted title key with the Wii U common key, as stored in the ticket.
/// IV = `title_id ++ 0*8`.
pub fn encrypt_title_key(common_key: &[u8; 16], title_id: u64, title_key: &[u8; 16]) -> [u8; 16] {
    let mut iv = [0u8; 16];
    iv[..8].copy_from_slice(&title_id.to_be_bytes());
    let mut buf = *title_key;
    <cbc::Encryptor<Aes128>>::new(common_key.into(), &iv.into())
        .encrypt_padded_mut::<NoPadding>(&mut buf, 16)
        .expect("16-byte buffer");
    buf
}

/// Decrypt an encrypted title key (as stored in a ticket or a title-key database) with the
/// Wii U common key. IV = `title_id ++ 0*8`. Inverse of [`encrypt_title_key`].
pub fn decrypt_title_key(common_key: &[u8; 16], title_id: u64, enc_title_key: &[u8; 16]) -> [u8; 16] {
    let mut iv = [0u8; 16];
    iv[..8].copy_from_slice(&title_id.to_be_bytes());
    let mut buf = *enc_title_key;
    <cbc::Decryptor<Aes128>>::new(common_key.into(), &iv.into())
        .decrypt_padded_mut::<NoPadding>(&mut buf)
        .expect("16-byte buffer");
    buf
}

/// Build a `title.tik` for `title_id` carrying the given encrypted title key.
pub fn build_ticket(title_id: u64, encrypted_title_key: &[u8; 16]) -> Vec<u8> {
    let mut out = Vec::with_capacity(TICKET_LEN);
    out.extend_from_slice(&SIG_TYPE_RSA2048_SHA256.to_be_bytes());
    out.extend_from_slice(&[0u8; SIG_BLOCK - 4]); // fakesigned signature + padding

    let mut body = TICKET_BODY_TEMPLATE;
    body[TITLE_KEY_OFF..TITLE_KEY_OFF + 16].copy_from_slice(encrypted_title_key);
    body[TITLE_ID_OFF..TITLE_ID_OFF + 8].copy_from_slice(&title_id.to_be_bytes());
    out.extend_from_slice(&body);

    debug_assert_eq!(out.len(), TICKET_LEN);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ticket_has_correct_layout() {
        let tik = build_ticket(0x0005000252535045, &[0xAB; 16]);
        assert_eq!(tik.len(), TICKET_LEN);
        assert_eq!(&tik[0..4], &[0x00, 0x01, 0x00, 0x04]);
        assert_eq!(&tik[0x140..0x140 + 26], b"Root-CA00000003-XS0000000c");
        assert_eq!(&tik[0x1BF..0x1CF], &[0xAB; 16]);
        assert_eq!(&tik[0x1DC..0x1E4], &0x0005000252535045u64.to_be_bytes());
        assert_eq!(tik[0x1F1], 0, "common key index = Wii U common key");
    }

    /// Reproduce a retail ticket body exactly (signature excluded) from its own title id and
    /// encrypted key.
    #[test]
    fn reproduces_reference_ticket_body() {
        let path =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.dev/wup_ref/title.tik");
        if !path.exists() {
            return;
        }
        let reference = std::fs::read(&path).unwrap();
        let title_id = u64::from_be_bytes(reference[0x1DC..0x1E4].try_into().unwrap());
        let mut key = [0u8; 16];
        key.copy_from_slice(&reference[0x1BF..0x1CF]);
        let ours = build_ticket(title_id, &key);
        assert_eq!(&ours[0x140..], &reference[0x140..], "ticket body differs from reference");
    }
}
