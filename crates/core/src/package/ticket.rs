//! The title ticket (`title.tik`), 0x350 bytes.
//!
//! The ticket carries the title key encrypted with the Wii U common key. Layout (big-endian),
//! verified against a retail title:
//!
//! ```text
//! 0x000  u32 signature type (0x00010004)
//! 0x004  0x100-byte signature (fakesigned: zero)
//! 0x104  padding to 0x140
//! 0x140  0x40 issuer  "Root-CA00000003-XS0000000c"
//! 0x180  0x3C ECDH public key (placeholder)
//! 0x1BF  0x10 encrypted title key
//! 0x1DC  0x08 title id
//! 0x1F1  0x01 common key index (0 = Wii U common key)
//! …      content-access permissions, to 0x350
//! ```

